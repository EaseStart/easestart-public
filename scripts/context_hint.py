#!/usr/bin/env python3
from __future__ import annotations
"""
Hint Layer — State-Aware Context Injection.

Reads STATE.md, taskboard.json, and agent-notes to generate a dynamic context
block for the start of each session. Replaces static prompt rules with
state-specific, actionable hints.

Usage:
    python3 scripts/context_hint.py
    python3 scripts/context_hint.py --json
"""
import argparse
import json
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
PM_DIR = PROJECT_ROOT / "pm"
STATE_FILE = PM_DIR / "STATE.md"
TASKBOARD_FILE = PM_DIR / "taskboard.json"
AGENT_NOTES_DIR = PM_DIR / "agent-notes"
BROADCAST_FILE = AGENT_NOTES_DIR / "_broadcast.md"
STATE_JSON_FILE = AGENT_NOTES_DIR / "_state.json"
SPECS_DIR = PROJECT_ROOT / "plans" / "specs"

STALE_THRESHOLD_DAYS = 3
VERY_STALE_THRESHOLD_DAYS = 7


def parse_state_md() -> dict:
    """Parse STATE.md into structured data."""
    state = {
        "stage": 0,
        "project": "",
        "current_focus": "",
        "active_blockers": "",
        "last_update": "",
        "last_test": "",
    }
    if not STATE_FILE.exists():
        state["_missing"] = True
        return state

    content = STATE_FILE.read_text(encoding="utf-8")
    patterns = {
        "stage": r"\*\*Stage:\*\*\s*(\d+)",
        "project": r"\*\*Project:\*\*\s*(.+?)(?:\n|$)",
        "current_focus": r"\*\*Current Focus:\*\*\s*(.+?)(?:\n|$)",
        "active_blockers": r"\*\*Active Blockers:\*\*\s*(.+?)(?:\n|$)",
        "last_update": r"\*\*Last Update:\*\*\s*(.+?)(?:\n|$)",
        "last_test": r"\*\*Last Test:\*\*\s*(.+?)(?:\n|$)",
    }
    for key, pattern in patterns.items():
        match = re.search(pattern, content)
        if match:
            val = match.group(1).strip()
            state[key] = int(val) if key == "stage" else val

    return state


def parse_date(date_str: str) -> datetime | None:
    """Try to parse common date formats."""
    for fmt in ["%Y-%m-%d", "%d/%m/%Y", "%m/%d/%Y"]:
        try:
            return datetime.strptime(date_str.strip(), fmt)
        except ValueError:
            continue
    return None


def load_taskboard() -> dict:
    """Load taskboard.json."""
    if not TASKBOARD_FILE.exists():
        return {}
    with open(TASKBOARD_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def load_agent_state() -> dict:
    """Load agent notes _state.json."""
    if not STATE_JSON_FILE.exists():
        return {}
    with open(STATE_JSON_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def get_pending_compliance() -> list[str]:
    """Check for features with incomplete compliance."""
    pending = []
    if not SPECS_DIR.exists():
        return pending

    for spec_dir in SPECS_DIR.iterdir():
        if not spec_dir.is_dir() or spec_dir.name.startswith("."):
            continue
        # Check if brainstorm exists but STATUS.md is missing (incomplete workflow)
        has_brainstorm = (spec_dir / "brainstorm.md").exists()
        has_status = (spec_dir / "STATUS.md").exists()
        has_blueprint = (spec_dir / "blueprint.md").exists()

        if has_brainstorm and not has_status:
            pending.append(f"{spec_dir.name}: has brainstorm but missing STATUS.md")
        elif has_blueprint and not has_status:
            pending.append(f"{spec_dir.name}: has blueprint but missing STATUS.md")

    return pending


class SessionHints:
    """Collects and formats session hints."""

    def __init__(self):
        self.hints: list[dict] = []

    def add(self, category: str, icon: str, message: str, priority: int = 5):
        self.hints.append({
            "category": category,
            "icon": icon,
            "message": message,
            "priority": priority,  # 1=highest, 10=lowest
        })

    def to_markdown(self) -> str:
        """Format hints as markdown block for session injection."""
        if not self.hints:
            return "✅ No active hints — all clear."

        sorted_hints = sorted(self.hints, key=lambda h: h["priority"])
        lines = [
            "## 🧭 Session Context (Auto-Generated)",
            "",
            "> Generated by `context_hint.py`. Review before proceeding.",
            "",
        ]

        for hint in sorted_hints:
            lines.append(f"- {hint['icon']} **{hint['category']}:** {hint['message']}")

        lines.append("")
        lines.append(f"_Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}_")
        return "\n".join(lines)

    def to_dict(self) -> list[dict]:
        return sorted(self.hints, key=lambda h: h["priority"])


def generate_hints() -> SessionHints:
    """Generate all session hints based on current state."""
    hints = SessionHints()
    state = parse_state_md()
    taskboard = load_taskboard()
    agent_state = load_agent_state()

    # --- STATE.md checks ---
    if state.get("_missing"):
        hints.add("State", "❌", "STATE.md not found. Run stage detection first.", priority=1)
        return hints  # Can't do much without state

    # Stale context warning
    if state["last_update"]:
        last_update = parse_date(state["last_update"])
        if last_update:
            days_old = (datetime.now() - last_update).days
            if days_old >= VERY_STALE_THRESHOLD_DAYS:
                hints.add(
                    "Stale Context", "🔴",
                    f"STATE.md is {days_old} days old. Confirm stage and focus before proceeding.",
                    priority=1,
                )
            elif days_old >= STALE_THRESHOLD_DAYS:
                hints.add(
                    "Context Age", "⚠️",
                    f"STATE.md is {days_old} days old. Quick check: still at Stage {state['stage']}?",
                    priority=3,
                )

    # Stage info
    hints.add(
        "Stage", "🎯",
        f"Stage {state['stage']} — Focus: {state['current_focus'][:100]}",
        priority=2,
    )

    # Active blockers
    blockers = state.get("active_blockers", "").strip()
    if blockers and blockers.lower() != "none":
        hints.add("Blockers", "🚧", f"Active blockers: {blockers}", priority=2)

    # --- Taskboard checks ---
    active_sprint = taskboard.get("active_sprint")
    if active_sprint:
        tasks = taskboard.get("tasks", [])
        total = len(tasks)
        done = sum(1 for t in tasks if t.get("status") == "complete")
        blocked = sum(1 for t in tasks if t.get("status") == "blocked")
        in_progress = sum(1 for t in tasks if t.get("status") == "in_progress")

        sprint_msg = f"Sprint '{active_sprint}': {done}/{total} tasks complete."
        if blocked:
            sprint_msg += f" ⚠️ {blocked} blocked."
        if in_progress:
            sprint_msg += f" {in_progress} in progress."

        hints.add("Sprint", "📋", sprint_msg, priority=3)

    # --- Agent notes checks ---
    if agent_state:
        last_agent = agent_state.get("last_agent", "")
        last_update_str = agent_state.get("last_update", "")
        if last_agent:
            last_date = parse_date(last_update_str) if last_update_str else None
            if last_date and (datetime.now() - last_date).days > VERY_STALE_THRESHOLD_DAYS:
                hints.add(
                    "Agent Context", "⚠️",
                    f"Agent notes from {last_agent} are stale ({last_update_str}). Re-confirm before applying.",
                    priority=4,
                )
            elif last_agent:
                hints.add(
                    "Last Agent", "🤖",
                    f"Last active agent: {last_agent}. Check upstream context if routing downstream.",
                    priority=6,
                )

    # --- Recent broadcasts ---
    if BROADCAST_FILE.exists():
        content = BROADCAST_FILE.read_text(encoding="utf-8")
        broadcast_lines = [
            line.strip() for line in content.split("\n")
            if line.strip().startswith("- [")
        ]
        if broadcast_lines:
            recent = broadcast_lines[-3:]  # Last 3 broadcasts
            hints.add(
                "Team Activity", "📡",
                "Recent: " + " | ".join(line[2:60] for line in recent),
                priority=7,
            )

    # --- Pending compliance ---
    pending = get_pending_compliance()
    if pending:
        hints.add(
            "Compliance", "🔍",
            f"{len(pending)} features with incomplete workflow: {', '.join(p.split(':')[0] for p in pending[:3])}",
            priority=4,
        )

    # --- Stage-specific hints ---
    stage = state["stage"]
    if stage < 2:
        hints.add(
            "Stage Guard", "🛡️",
            "Growth/marketing advice is BLOCKED at this stage. Focus on validation.",
            priority=5,
        )
    elif stage < 4:
        hints.add(
            "Stage Guard", "🛡️",
            "Fundraising/scaling blocked until PMF confirmed (Stage 4+).",
            priority=5,
        )

    return hints


def main():
    parser = argparse.ArgumentParser(
        description="Hint Layer — State-Aware Context Injection"
    )
    parser.add_argument("--json", action="store_true", help="Output as JSON")
    args = parser.parse_args()

    hints = generate_hints()

    if args.json:
        print(json.dumps(hints.to_dict(), indent=2))
    else:
        print(hints.to_markdown())


if __name__ == "__main__":
    main()
